import { generateExercises, VocabItem } from './exercise-generator';

interface Lesson { id: string; title: string; order: number; unit: string; questions: any[]; }

function v(word: string, translation: string, tr: string, ex?: string, exAr?: string): VocabItem {
  return { word, translation, transliteration: tr, ...(ex && { example: ex, exampleAr: exAr }) };
}

function buildUnit(grade: number, unitNum: number, title: string, vocab: VocabItem[]): Lesson[] {
  return Array.from({ length: 10 }, (_, i) => {
    const l = i + 1;
    const id = `ar${grade}-u${unitNum}-l${l}`;
    return { id, title: l === 10 ? `اختبار: ${title}` : `${title} (${l})`, order: (unitNum - 1) * 10 + l, unit: title, questions: generateExercises(id, vocab) };
  });
}

