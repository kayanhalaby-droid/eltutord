import { generateExercises, VocabItem } from './exercise-generator';

interface Lesson { id: string; title: string; order: number; unit: string; questions: any[]; }

function u(w: string, t: string, tr: string, g?: 'male'|'female', ex?: string, exAr?: string): VocabItem {
  return { word: w, translation: t, transliteration: tr, ...(g && { gender: g }), ...(ex && { example: ex, exampleAr: exAr }) };
}

function buildUnit(grade: number, unitNum: number, title: string, vocab: VocabItem[]): Lesson[] {
  return Array.from({ length: 10 }, (_, i) => {
    const l = i + 1;
    const id = `hb${grade}-u${unitNum}-l${l}`;
    return { id, title: l === 10 ? `בחן את עצמך — ${title}` : `${title} (${l})`, order: (unitNum - 1) * 10 + l, unit: title, questions: generateExercises(id, vocab) };
  });
}

