export function wordToEmoji(word: string): string {
  if (!word) return '🖼️';
  // Direct match
  const direct = EMOJI_MAP[word.trim()];
  if (direct) return direct;
  // Partial match — first key that appears in the word
  for (const [key, emoji] of Object.entries(EMOJI_MAP)) {
    if (word.includes(key)) return emoji;
  }
  return '🖼️';
}
